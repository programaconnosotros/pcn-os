// Writes the snapshot of prisma/schema.prisma that /desarrollo draws as an ER diagram.
// Run it after changing the schema (and `prisma generate`): `pnpm db:diagram`.
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'src/app/(platform)/desarrollo/db-schema.ts';

// Which part of the site each model belongs to; a new model must be added here.
const DOMAINS = {
  comunidad: [
    'User',
    'UserPosition',
    'UserLanguage',
    'UserStackItem',
    'Badge',
    'UserBadge',
    'Testimonial',
    'ContentMark',
    'IdentityLink',
    'Notification',
    'PushSubscription',
    'Setup',
    'WorkPlace',
    'SetupLike',
    'Recommendation',
  ],
  consejos: ['Advice', 'Comment', 'Like', 'CommentLike', 'HiddenConsejo'],
  foro: ['ForumCategory', 'ForumPost', 'ForumComment', 'ForumPostLike', 'ForumCommentLike'],
  eventos: [
    'Event',
    'EventOrganizer',
    'EventRegistration',
    'EventWaitlistEntry',
    'EventFlyerDesigner',
    'EventBroadcast',
    'Sponsor',
    'SponsorClick',
    'Announcement',
  ],
  charlas: ['TalkProposal', 'TalkProposalSpeaker', 'Talk', 'TalkSpeaker'],
  galeria: ['GalleryItem', 'GalleryItemTag'],
  proyectos: ['Project', 'ProjectMember', 'ProjectMedia', 'ArticleAuthor'],
  auth: [
    'Session',
    'PasswordResetToken',
    'EmailVerificationToken',
    'TwoFactorChallenge',
    'OAuthClient',
    'OAuthAuthorizationCode',
    'OAuthToken',
  ],
  sistema: [
    'PageVisit',
    'ErrorLog',
    'AppLog',
    'SystemAlert',
    'ContentReport',
    'HiddenFeedItem',
    'JobOffers',
  ],
};

const domainOf = Object.fromEntries(
  Object.entries(DOMAINS).flatMap(([domain, models]) => models.map((model) => [model, domain])),
);

// Lo escribe el generator `datamodel` del schema en cada `prisma generate`.
const { models, enums } = JSON.parse(
  readFileSync('src/generated/datamodel/datamodel.json', 'utf8'),
);
const missing = models.map((m) => m.name).filter((name) => !domainOf[name]);
if (missing.length) throw new Error(`Sin dominio en DOMAINS: ${missing.join(', ')}`);

const relations = [];
const out = models.map((model) => {
  const fkFields = new Set(model.fields.flatMap((f) => f.relationFromFields ?? []));
  for (const field of model.fields) {
    if (field.kind !== 'object' || !field.relationFromFields?.length) continue;
    const back = models
      .find((m) => m.name === field.type)
      .fields.find((f) => f.relationName === field.relationName && f !== field);
    relations.push({
      from: model.name,
      to: field.type,
      label: field.name,
      optional: !field.isRequired,
      many: back ? back.isList : true,
      onDelete: field.relationOnDelete ?? null,
    });
  }
  return {
    name: model.name,
    domain: domainOf[model.name],
    fields: model.fields
      .filter((f) => f.kind !== 'object')
      .map((f) => ({
        name: f.name,
        type: f.type,
        ...(f.isId && { pk: true }),
        ...(fkFields.has(f.name) && { fk: true }),
        ...(f.isUnique && { unique: true }),
        ...(!f.isRequired && { optional: true }),
        ...(f.isList && { list: true }),
      })),
    uniques: model.uniqueFields,
  };
});

const today = new Date().toISOString().slice(0, 10);
const json = (value) => JSON.stringify(value, null, 2);

writeFileSync(
  OUT,
  `// Generated by scripts/generate-db-schema.mjs from prisma/schema.prisma — don't edit by hand.

export type DbField = {
  name: string;
  type: string;
  pk?: boolean;
  fk?: boolean;
  unique?: boolean;
  optional?: boolean;
  list?: boolean;
};

export type DbModel = {
  name: string;
  domain: DbDomain;
  fields: DbField[];
  /** Composite unique constraints (\`@@unique\`). */
  uniques: string[][];
};

/** A foreign key: \`from\` holds it and points at \`to\`. \`many\`: \`to\` has many \`from\`. */
export type DbRelation = {
  from: string;
  to: string;
  label: string;
  optional: boolean;
  many: boolean;
  onDelete: string | null;
};

export type DbDomain = ${Object.keys(DOMAINS)
    .map((d) => `'${d}'`)
    .join(' | ')};

export const DB_SCHEMA_UPDATED_AT = '${today}';

export const dbEnums: { name: string; values: string[] }[] = ${json(
    enums.map((e) => ({ name: e.name, values: e.values.map((v) => v.name) })),
  )};

export const dbModels: DbModel[] = ${json(out)};

export const dbRelations: DbRelation[] = ${json(relations)};
`,
);
console.log(`${OUT}: ${out.length} models, ${relations.length} relations`);
